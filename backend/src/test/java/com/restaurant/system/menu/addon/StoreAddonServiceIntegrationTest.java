    @Test
    void sameItemEqualParentAndEligibilityDuplicatesPreserveBothIds() {
        long first = option(10, "beef", "牛肉", "Beef", "2.00", true);
        long second = option(10, "beef", "牛肉", "Beef", "2.00", true);
        long parent = option(10, "parent", "父选项", "Parent", "0.00", true);
        jdbc.update("update menu_item_options set option_group='REMOVE',option_type='remove' where id=?", parent);
        jdbc.update("update menu_item_options set parent_option_id=? where id in (?,?)", parent, first, second);
        var report = service.reconcile(1L, false);
        assertThat(report.conflicts()).isEmpty();
        assertThat(report.linked_options()).isEqualTo(2);
        assertThat(jdbc.queryForList("select id from menu_item_options where store_addon_id is not null order by id", Long.class))
            .containsExactly(first, second);
        assertThat(jdbc.queryForList("select parent_option_id from menu_item_options where store_addon_id is not null", Long.class))
            .containsExactly(parent, parent);
        assertThat(service.reconcile(1L, false).linked_options()).isZero();
    }

    @Test
    void linkedEligibilityDifferenceIsStillAmbiguousWhenCatalogInactiveMasksActiveDifference() {
        var addon = service.create(request(1, "beef", "牛肉", "Beef", "2.00", false));
        long first = option(10, "beef", "牛肉", "Beef", "2.00", false);
        long second = option(10, "beef", "牛肉", "Beef", "2.00", false);
        jdbc.update("update menu_item_options set store_addon_id=?,store_addon_store_id=1,addon_eligible=true where id=?", addon.id(), first);
        jdbc.update("update menu_item_options set store_addon_id=?,store_addon_store_id=1,addon_eligible=false where id=?", addon.id(), second);
        var before = jdbc.queryForList("select * from menu_item_options order by id");
        var dry = service.reconcile(1L, true);
        assertThat(dry.conflicts()).singleElement().satisfies(c -> assertThat(c.reason()).isEqualTo("ADDON_RELATIONSHIP_CONFLICT"));
        assertThat(service.reconcile(1L, false).conflicts()).isEqualTo(dry.conflicts());
        assertThat(service.reconcile(1L, false).conflicts()).isEqualTo(dry.conflicts());
        assertThatThrownBy(() -> service.setEligibility(10L, addon.id(), true)).hasMessageContaining("ADDON_RELATIONSHIP_CONFLICT");
        assertThat(jdbc.queryForList("select * from menu_item_options order by id")).isEqualTo(before);
        assertThat(revision(1)).isEqualTo(2);
    }

    private void assertUnlinkedRelationshipConflictPreserved(Long... optionIds) {
        var before = jdbc.queryForList("select * from menu_item_options order by id");
        var conflicts = service.getAddons(1L).conflicts();
        assertThat(conflicts).singleElement().satisfies(c -> {
            assertThat(c.reason()).isEqualTo("ADDON_RELATIONSHIP_CONFLICT");
            assertThat(c.option_ids()).containsExactly(optionIds);
        });
        for (boolean dryRun : List.of(true, false, false)) {
            var result = service.reconcile(1L, dryRun);
            assertThat(result.conflicts()).isEqualTo(conflicts);
            assertThat(result.linked_groups()).isZero();
            assertThat(result.linked_options()).isZero();
            assertThat(jdbc.queryForList("select * from menu_item_options order by id")).isEqualTo(before);
        }
        assertThat(count("store_addons")).isZero();
        assertThat(count("organization_addon_definitions")).isZero();
        assertThat(revision(1)).isEqualTo(1);
    }

    @Test
    void catalogRenameAndRepricePropagateAllRowsAndEligibilitySurvivesActiveCycle() {
        long first = option(10, "beef", "牛肉", "Beef", "2.00", true);
        option(11, "beef", "牛肉", "Beef", "2.00", false);
        jdbc.update("insert into order_item_options values (100,?,'牛肉',2.00)", first);
        service.reconcile(1L, false);
        var addon = service.getAddons(1L).addons().get(0);
        service.update(addon.id(), request(1, "beef", "精选牛肉", "Premium beef", "3.25", false));
        assertThat(jdbc.queryForList("select is_active from menu_item_options", Boolean.class)).containsOnly(false);
        assertThat(jdbc.queryForList("select name_zh from menu_item_options", String.class)).containsOnly("精选牛肉");
        assertThat(jdbc.queryForList("select price_delta from menu_item_options", BigDecimal.class)).containsOnly(new BigDecimal("3.25"));
        assertThat(service.getItemAddons(10L).get(0).enabled()).isTrue();
        assertThat(service.getItemAddons(11L).get(0).enabled()).isFalse();
        service.update(addon.id(), request(1, null, "精选牛肉", "Premium beef", "3.25", true));
        assertThat(jdbc.queryForList("select is_active from menu_item_options order by id", Boolean.class)).containsExactly(true, false);
        assertThat(jdbc.queryForMap("select name_zh,price_delta from order_item_options where id=100"))
            .containsEntry("name_zh", "牛肉").containsEntry("price_delta", new BigDecimal("2.00"));
        assertThat(jdbc.queryForObject("select id from menu_item_options where menu_item_id=10", Long.class)).isEqualTo(first);
    }

