    @Test
    void duplicateConcurrentCreationAndEligibilityAreSerialized() throws Exception {
        var executor = Executors.newFixedThreadPool(2);
        try {
            var start = new CountDownLatch(1);
            var futures = java.util.stream.IntStream.range(0, 2).mapToObj(n -> executor.submit(() -> {
                start.await();
                try { service.create(request(1, "beef", "牛肉", "Beef", "2.00", true)); return "created"; }
                catch (BusinessException e) { return e.getMessage(); }
            })).toList();
            start.countDown();
            List<String> results = List.of(futures.get(0).get(10, TimeUnit.SECONDS), futures.get(1).get(10, TimeUnit.SECONDS));
            assertThat(results).contains("created").anySatisfy(r -> assertThat(r).startsWith("ADDON_CODE_EXISTS"));
            assertThat(count("store_addons")).isEqualTo(1);
            Long id = service.getAddons(1L).addons().get(0).id();
            var a = executor.submit(() -> service.setEligibility(10L, id, true));
            var b = executor.submit(() -> service.setEligibility(10L, id, true));
            a.get(10, TimeUnit.SECONDS); b.get(10, TimeUnit.SECONDS);
            assertThat(count("menu_item_options")).isEqualTo(1);
        } finally { executor.shutdownNow(); }
    }

    @Test
    void twoStoresConcurrentlyShareOneOrganizationDefinition() throws Exception {
        var executor = Executors.newFixedThreadPool(2);
        try {
            var start = new CountDownLatch(1);
            var a = executor.submit(() -> { start.await(); return service.create(request(1, "beef", "牛肉", "Beef", "2.00", true)); });
            var b = executor.submit(() -> { start.await(); return service.create(request(2, "beef", "牛肉", "Beef", "4.00", true)); });
            start.countDown(); a.get(10, TimeUnit.SECONDS); b.get(10, TimeUnit.SECONDS);
            assertThat(count("organization_addon_definitions")).isEqualTo(1);
            assertThat(count("store_addons")).isEqualTo(2);
        } finally { executor.shutdownNow(); }
    }

