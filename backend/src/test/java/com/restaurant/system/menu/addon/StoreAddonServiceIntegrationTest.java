    @Test
    void reconciliationParticipatesInOuterProvisioningTransaction() {
        option(10, "beef", "牛肉", "Beef", "2.00", true);
        assertThatThrownBy(() -> new TransactionTemplate(transactionManager).execute(status -> {
            service.reconcile(1L, false);
            assertThat(count("store_addons")).isEqualTo(1);
            throw new BusinessException("PROVISIONING_LATE_FAILURE");
        })).hasMessage("PROVISIONING_LATE_FAILURE");
        assertThat(count("store_addons")).isZero();
        assertThat(revision(1)).isEqualTo(1);
    }

    private long option(long itemId, String code, String zh, String en, String price, boolean active) {
        jdbc.update("""
            insert into menu_item_options(menu_item_id,option_type,option_group,option_code,name_zh,name_en,price_delta,is_active)
            values (?,'addon','ADD_ON',?,?,?,?,?)
            """, itemId, code, zh, en, new BigDecimal(price), active);
        return jdbc.queryForObject("select max(id) from menu_item_options", Long.class);
    }

    private StoreAddonService.WriteRequest request(long store, String code, String zh, String en, String price, boolean active) {
        var request = new StoreAddonService.WriteRequest();
        request.store_id = store; request.code = code; request.name_zh = zh; request.name_en = en;
        request.price = new BigDecimal(price); request.active = active; return request;
    }
    private long count(String table) { return jdbc.queryForObject("select count(*) from " + table, Long.class); }
    private long revision(long storeId) { return jdbc.queryForObject("select menu_revision from stores where id=?", Long.class, storeId); }
