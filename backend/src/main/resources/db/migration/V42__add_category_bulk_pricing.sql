-- Explicit Store opt-in only. This migration never enables a restaurant or changes prices.
ALTER TABLE public.store_pricing_policies
    ADD COLUMN category_bulk_pricing_enabled boolean NOT NULL DEFAULT false;

CREATE TABLE public.store_category_price_adjustment_previews (
    preview_id varchar(36) PRIMARY KEY,
    store_id bigint NOT NULL REFERENCES public.stores(id),
    body_hash varchar(64) NOT NULL,
    menu_revision bigint NOT NULL,
    before_fingerprint varchar(64) NOT NULL,
    expires_at timestamp with time zone NOT NULL,
    created_at timestamp with time zone NOT NULL DEFAULT current_timestamp
);

CREATE INDEX idx_category_price_previews_store_expiry
    ON public.store_category_price_adjustment_previews(store_id, expires_at);

CREATE TABLE public.store_category_price_adjustments (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    store_id bigint NOT NULL REFERENCES public.stores(id),
    idempotency_key varchar(128) NOT NULL,
    body_hash varchar(64) NOT NULL,
    preview_id varchar(36) NOT NULL REFERENCES public.store_category_price_adjustment_previews(preview_id),
    response_json text NOT NULL,
    created_at timestamp with time zone NOT NULL DEFAULT current_timestamp,
    CONSTRAINT uq_category_price_adjustments_store_key UNIQUE(store_id, idempotency_key)
);
