CREATE OR REPLACE FUNCTION public.enforce_chain_master_menu_version_immutable()
RETURNS trigger AS $$
BEGIN
    IF OLD.status IN ('PUBLISHED', 'RETIRED') AND (
            NEW.master_menu_id IS DISTINCT FROM OLD.master_menu_id
            OR NEW.version_key IS DISTINCT FROM OLD.version_key
            OR (
                NEW.status IS DISTINCT FROM OLD.status
                AND NOT (OLD.status = 'PUBLISHED' AND NEW.status = 'RETIRED')
            )
            OR NEW.schema_version IS DISTINCT FROM OLD.schema_version
            OR NEW.content_json IS DISTINCT FROM OLD.content_json
            OR NEW.fingerprint_sha256 IS DISTINCT FROM OLD.fingerprint_sha256
            OR NEW.source_profile_code IS DISTINCT FROM OLD.source_profile_code
            OR NEW.source_profile_version IS DISTINCT FROM OLD.source_profile_version
            OR NEW.source_profile_fingerprint_sha256 IS DISTINCT FROM OLD.source_profile_fingerprint_sha256
            OR NEW.source_reference IS DISTINCT FROM OLD.source_reference
            OR NEW.published_at IS DISTINCT FROM OLD.published_at
        ) THEN
        RAISE EXCEPTION 'CHAIN_MASTER_MENU_VERSION_IMMUTABLE';
    END IF;
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER trg_chain_master_menu_versions_immutable
BEFORE UPDATE ON public.chain_master_menu_versions
FOR EACH ROW
EXECUTE FUNCTION public.enforce_chain_master_menu_version_immutable();
