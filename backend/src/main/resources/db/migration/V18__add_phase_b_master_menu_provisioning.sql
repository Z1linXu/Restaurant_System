-- V18__add_phase_b_master_menu_provisioning
-- Phase B Part 1: chain master menu identity, store lifecycle provenance,
-- and owner store provisioning ledger. Additive schema only.

ALTER TABLE public.stores
    ADD COLUMN store_kind character varying(32) NOT NULL DEFAULT 'BUSINESS',
    ADD COLUMN lifecycle_status character varying(32) NOT NULL DEFAULT 'ACTIVE',
    ADD COLUMN provisioning_source character varying(64) NOT NULL DEFAULT 'LEGACY_EXISTING_STORE',
    ADD COLUMN provisioned_profile_code character varying(96),
    ADD COLUMN provisioned_profile_version character varying(64),
    ADD COLUMN provisioned_profile_fingerprint_sha256 character(64),
    ADD COLUMN provisioned_master_menu_key character varying(96),
    ADD COLUMN provisioned_master_menu_version character varying(64),
    ADD COLUMN provisioned_master_menu_fingerprint_sha256 character(64);

ALTER TABLE public.stores
    ADD CONSTRAINT chk_stores_store_kind
        CHECK (store_kind IN ('BUSINESS', 'VALIDATION_FIXTURE')),
    ADD CONSTRAINT chk_stores_lifecycle_status
        CHECK (lifecycle_status IN (
            'CONFIGURING',
            'READY_FOR_REVIEW',
            'ACTIVE',
            'INACTIVE',
            'PROVISIONING_FAILED'
        )),
    ADD CONSTRAINT chk_stores_provisioning_source
        CHECK (provisioning_source IN (
            'LEGACY_EXISTING_STORE',
            'PHASE_B_OWNER_PROVISIONING',
            'STAGING_VALIDATION'
        )),
    ADD CONSTRAINT chk_stores_provisioned_profile_fingerprint
        CHECK (
            provisioned_profile_fingerprint_sha256 IS NULL
            OR provisioned_profile_fingerprint_sha256 ~ '^[0-9a-f]{64}$'
        ),
    ADD CONSTRAINT chk_stores_provisioned_master_menu_fingerprint
        CHECK (
            provisioned_master_menu_fingerprint_sha256 IS NULL
            OR provisioned_master_menu_fingerprint_sha256 ~ '^[0-9a-f]{64}$'
        );

CREATE TABLE public.chain_master_menus (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    organization_id bigint NOT NULL,
    master_menu_key character varying(96) NOT NULL,
    display_name character varying(255) NOT NULL,
    description text,
    status character varying(32) NOT NULL,
    provenance character varying(255) NOT NULL,
    created_at timestamp(6) without time zone NOT NULL,
    updated_at timestamp(6) without time zone NOT NULL,
    CONSTRAINT uq_chain_master_menus_org_key UNIQUE (organization_id, master_menu_key),
    CONSTRAINT fk_chain_master_menus_organization
        FOREIGN KEY (organization_id) REFERENCES public.organizations(id),
    CONSTRAINT chk_chain_master_menus_key
        CHECK (master_menu_key ~ '^[A-Z0-9][A-Z0-9_:-]*$'),
    CONSTRAINT chk_chain_master_menus_status
        CHECK (status IN ('DRAFT', 'PUBLISHED', 'RETIRED'))
);

CREATE TABLE public.chain_master_menu_versions (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    master_menu_id bigint NOT NULL,
    version_key character varying(64) NOT NULL,
    status character varying(32) NOT NULL,
    schema_version character varying(64) NOT NULL,
    content_json text NOT NULL,
    fingerprint_sha256 character(64) NOT NULL,
    source_profile_code character varying(96) NOT NULL,
    source_profile_version character varying(64) NOT NULL,
    source_profile_fingerprint_sha256 character(64) NOT NULL,
    source_reference character varying(255) NOT NULL,
    created_at timestamp(6) without time zone NOT NULL,
    updated_at timestamp(6) without time zone NOT NULL,
    published_at timestamp(6) without time zone,
    CONSTRAINT uq_chain_master_menu_versions_key UNIQUE (master_menu_id, version_key),
    CONSTRAINT uq_chain_master_menu_versions_fingerprint UNIQUE (master_menu_id, fingerprint_sha256),
    CONSTRAINT fk_chain_master_menu_versions_menu
        FOREIGN KEY (master_menu_id) REFERENCES public.chain_master_menus(id),
    CONSTRAINT chk_chain_master_menu_versions_version
        CHECK (version_key ~ '^[A-Za-z0-9][A-Za-z0-9._:-]*$'),
    CONSTRAINT chk_chain_master_menu_versions_status
        CHECK (status IN ('DRAFT', 'PUBLISHED', 'RETIRED')),
    CONSTRAINT chk_chain_master_menu_versions_schema
        CHECK (schema_version = 'CHAIN_MASTER_MENU_V1'),
    CONSTRAINT chk_chain_master_menu_versions_content_json
        CHECK (content_json IS NOT NULL AND left(btrim(content_json), 1) = '{'),
    CONSTRAINT chk_chain_master_menu_versions_fingerprint
        CHECK (fingerprint_sha256 ~ '^[0-9a-f]{64}$'),
    CONSTRAINT chk_chain_master_menu_versions_profile_fingerprint
        CHECK (source_profile_fingerprint_sha256 ~ '^[0-9a-f]{64}$'),
    CONSTRAINT chk_chain_master_menu_versions_published_at
        CHECK ((status = 'PUBLISHED' AND published_at IS NOT NULL) OR status IN ('DRAFT', 'RETIRED'))
);

