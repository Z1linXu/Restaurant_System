CREATE TABLE public.store_menu_master_mappings (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    store_id bigint NOT NULL,
    master_menu_version_id bigint NOT NULL,
    entity_type character varying(32) NOT NULL,
    local_entity_id bigint NOT NULL,
    master_category_key character varying(128),
    master_product_key character varying(128),
    master_option_key character varying(128),
    origin character varying(32) NOT NULL,
    mapping_status character varying(32) NOT NULL,
    created_at timestamp(6) without time zone NOT NULL,
    updated_at timestamp(6) without time zone NOT NULL,
    CONSTRAINT uq_store_menu_master_mappings_local UNIQUE (
        store_id,
        entity_type,
        local_entity_id
    ),
    CONSTRAINT fk_store_menu_master_mappings_store
        FOREIGN KEY (store_id) REFERENCES public.stores(id),
    CONSTRAINT fk_store_menu_master_mappings_version
        FOREIGN KEY (master_menu_version_id) REFERENCES public.chain_master_menu_versions(id),
    CONSTRAINT chk_store_menu_master_mappings_entity_type
        CHECK (entity_type IN ('CATEGORY', 'ITEM', 'OPTION')),
    CONSTRAINT chk_store_menu_master_mappings_origin
        CHECK (origin IN ('MASTER', 'STORE_ONLY')),
    CONSTRAINT chk_store_menu_master_mappings_status
        CHECK (mapping_status IN ('ACTIVE', 'LOCALLY_DEACTIVATED', 'STORE_ONLY')),
    CONSTRAINT chk_store_menu_master_mappings_identity
        CHECK (
            (
                origin = 'STORE_ONLY'
                AND mapping_status = 'STORE_ONLY'
                AND master_category_key IS NULL
                AND master_product_key IS NULL
                AND master_option_key IS NULL
            )
            OR (
                origin = 'MASTER'
                AND mapping_status IN ('ACTIVE', 'LOCALLY_DEACTIVATED')
                AND (
                    (entity_type = 'CATEGORY' AND master_category_key IS NOT NULL
                        AND master_product_key IS NULL AND master_option_key IS NULL)
                    OR (entity_type = 'ITEM' AND master_product_key IS NOT NULL
                        AND master_option_key IS NULL)
                    OR (entity_type = 'OPTION' AND master_option_key IS NOT NULL)
                )
            )
        )
);

