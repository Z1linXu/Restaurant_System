-- Additive, Store-private free Remove catalog. No legacy or historical data is rewritten.
CREATE TABLE public.store_removes (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 store_id bigint NOT NULL REFERENCES public.stores(id),
 code varchar(255) NOT NULL,
 name_zh varchar(255) NOT NULL,
 name_en varchar(255),
 active boolean NOT NULL,
 sort_order integer NOT NULL DEFAULT 0,
 created_at timestamp(6) NOT NULL,
 updated_at timestamp(6) NOT NULL,
 CONSTRAINT uq_store_removes_code UNIQUE(store_id,code),
 CONSTRAINT uq_store_removes_scope UNIQUE(id,store_id),
 CONSTRAINT chk_store_removes_code CHECK(code ~ '^[a-z][a-z0-9]*(_[a-z0-9]+)*$')
);
ALTER TABLE public.menu_categories ADD CONSTRAINT uq_menu_categories_remove_store_scope UNIQUE(id,store_id);
CREATE TABLE public.store_remove_categories (
 remove_id bigint NOT NULL,
 store_id bigint NOT NULL,
 category_id bigint NOT NULL,
 PRIMARY KEY(remove_id,category_id),
 FOREIGN KEY(remove_id,store_id) REFERENCES public.store_removes(id,store_id),
 FOREIGN KEY(category_id,store_id) REFERENCES public.menu_categories(id,store_id) ON DELETE CASCADE
);
CREATE TABLE public.store_remove_item_rules (
 remove_id bigint NOT NULL,
 store_id bigint NOT NULL,
 menu_item_id bigint NOT NULL,
 mode varchar(16) NOT NULL CHECK(mode IN ('ALLOW','DENY')),
 PRIMARY KEY(remove_id,menu_item_id),
 FOREIGN KEY(remove_id,store_id) REFERENCES public.store_removes(id,store_id),
 FOREIGN KEY(menu_item_id,store_id) REFERENCES public.menu_items(id,store_id) ON DELETE CASCADE
);
ALTER TABLE public.menu_item_options ADD COLUMN store_remove_id bigint;
ALTER TABLE public.menu_item_options ADD COLUMN store_remove_store_id bigint;
ALTER TABLE public.menu_item_options ADD CONSTRAINT fk_menu_item_options_remove_store
 FOREIGN KEY(store_remove_id,store_remove_store_id) REFERENCES public.store_removes(id,store_id);
ALTER TABLE public.menu_item_options ADD CONSTRAINT fk_menu_item_options_remove_item_store
 FOREIGN KEY(menu_item_id,store_remove_store_id) REFERENCES public.menu_items(id,store_id);
ALTER TABLE public.menu_item_options ADD CONSTRAINT chk_menu_item_options_remove_link CHECK (
 (store_remove_id IS NULL AND store_remove_store_id IS NULL) OR
 (store_remove_id IS NOT NULL AND store_remove_store_id IS NOT NULL AND menu_item_id IS NOT NULL
 AND store_addon_id IS NULL AND option_type IS NOT NULL AND option_type='remove'
 AND option_group IS NOT NULL AND option_group='REMOVE'
 AND parent_option_id IS NULL AND price_delta IS NOT NULL AND price_delta=0)
);
CREATE INDEX idx_menu_item_options_store_remove ON public.menu_item_options(store_remove_id);
CREATE FUNCTION public.enforce_store_remove_identity() RETURNS trigger AS $$
BEGIN
 IF NEW.store_id IS DISTINCT FROM OLD.store_id OR NEW.code IS DISTINCT FROM OLD.code THEN
  RAISE EXCEPTION 'REMOVE_CODE_IMMUTABLE';
 END IF;
 RETURN NEW;
END;
$$ LANGUAGE plpgsql;
CREATE TRIGGER trg_store_remove_identity BEFORE UPDATE ON public.store_removes
 FOR EACH ROW EXECUTE FUNCTION public.enforce_store_remove_identity();
